_GL = {k: np.array([[c == '1' for c in row] for row in v.split()], bool) for k, v in _G.items()}


def text_mask(text, scale=2):
    text = ''.join(ch if ch in _GL else ch.upper() for ch in text)
    cols = []
    for ch in text:
        g = _GL.get(ch, _GL[' '])
        cols.append(g); cols.append(np.zeros((7, 1), bool))
    m = np.concatenate(cols[:-1], 1) if cols else np.zeros((7, 0), bool)
    return np.repeat(np.repeat(m, scale, 0), scale, 1)


def draw_text(img, x, y, text, scale=2, rgb=(236, 232, 214), align='center', shadow=(8, 10, 18), alpha=1.0):
    """Draw onto an [H, W, 3] uint8 array. (x, y) is the top anchor; align: left|center|right."""
    m = text_mask(text, scale)
    h, w = m.shape
    x0 = int(round(x - (w / 2 if align == 'center' else w if align == 'right' else 0)))
    y0 = int(round(y))
    H, W = img.shape[:2]

    def put(mask, ox, oy, col, a):
        ya, yb, xa, xb = max(oy, 0), min(oy + h, H), max(ox, 0), min(ox + w, W)
        if ya >= yb or xa >= xb:
            return
        mm = mask[ya - oy:yb - oy, xa - ox:xb - ox]
        reg = img[ya:yb, xa:xb]
        reg[mm] = (reg[mm] * (1 - a) + np.array(col) * a).astype(np.uint8)
    if shadow is not None:
        for dx in (-scale, 0, scale):
            for dy in (-scale, 0, scale):
                if dx or dy:
                    put(m, x0 + dx, y0 + dy, shadow, alpha * 0.85)
    put(m, x0, y0, rgb, alpha)
    return w, h
